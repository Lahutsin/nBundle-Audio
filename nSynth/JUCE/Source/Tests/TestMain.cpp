// nSynthTests: runs every juce::UnitTest in the "nSynth" category.
//   nSynthTests                      run all tests (exit code 1 on failure)
//   nSynthTests --list               list test names
//   nSynthTests --only "<name>"      run a single test
//   nSynthTests --dump-params <file> write the Markdown parameter table (docs/02-PARAMETERS.md)
//   nSynthTests --snapshot <file.png> [scale] [--browser]  render the editor (optionally with the
//                                    preset browser open) to a PNG (docs/Plugin.png)
#include <juce_gui_basics/juce_gui_basics.h>
#include "Core/Params/ParamRegistry.h"
#include "PluginProcessor.h"
#include "PluginEditor.h"

using namespace nsynth;

namespace
{
juce::String rangeText (const ParamSpec& s)
{
    switch (s.kind)
    {
        case Kind::choiceParam: return s.choices.joinIntoString (" / ");
        case Kind::boolParam:   return "Off / On";
        case Kind::intParam:    return juce::String ((int) s.minValue) + " .. " + juce::String ((int) s.maxValue);
        case Kind::floatParam:  break;
    }
    juce::String m = s.mapping == Mapping::exponential ? " (exp)" : s.mapping == Mapping::skewed ? " (skew)" : "";
    return juce::String (s.minValue, 3) + " .. " + juce::String (s.maxValue, 3) + m;
}

juce::String defaultText (const ParamSpec& s)
{
    switch (s.kind)
    {
        case Kind::choiceParam: return s.choices[(int) s.defaultValue];
        case Kind::boolParam:   return s.defaultValue > 0.5f ? "On" : "Off";
        case Kind::intParam:    return juce::String ((int) s.defaultValue);
        case Kind::floatParam:  break;
    }
    return juce::String (s.defaultValue, 3);
}

juce::String table (const std::vector<ParamSpec>& specs, const juce::String& idPrefix)
{
    juce::String md;
    md << "| ID | Name | Section | Range | Default | Unit | CC | Notes |\n";
    md << "|---|---|---|---|---|---|---|---|\n";
    for (auto& s : specs)
        md << "| `" << idPrefix << s.suffix << "` | " << s.name << " | " << sectionName (s.section) << " | " << rangeText (s)
           << " | " << defaultText (s) << " | " << s.unit << " | " << (s.midiCC >= 0 ? juce::String (s.midiCC) : "-")
           << " | " << s.notes << " |\n";
    return md;
}

bool dumpParams (const juce::File& file)
{
    juce::String md;
    md << "<!-- GENERATED by `nSynthTests --dump-params` from Source/Core/Params/ParamRegistry.cpp. Do not edit by hand. -->\n\n";
    md << "### Layer parameters (" << (int) getLayerParamSpecs().size() << " per layer, prefix `up_` = UPPER, `lo_` = LOWER)\n\n";
    md << table (getLayerParamSpecs(), "{up,lo}_");
    md << "\n### Performance parameters (" << (int) getPerformanceParamSpecs().size() << ")\n\n";
    md << table (getPerformanceParamSpecs(), "perf_");
    md << "\nTotal automatable parameters: " << (int) (2 * getLayerParamSpecs().size() + getPerformanceParamSpecs().size()) << "\n";
    return file.replaceWithText (md);
}
} // namespace

int main (int argc, char* argv[])
{
    juce::ScopedJuceInitialiser_GUI gui;
    juce::StringArray args;
    for (int i = 1; i < argc; ++i)
        args.add (argv[i]);

    if (args.contains ("--dump-params"))
    {
        const auto path = args[args.indexOf ("--dump-params") + 1];
        const bool ok = dumpParams (juce::File::getCurrentWorkingDirectory().getChildFile (path));
        std::cout << (ok ? "Wrote " : "FAILED to write ") << path << std::endl;
        return ok ? 0 : 1;
    }

    if (args.contains ("--snapshot"))
    {
        const auto path = args[args.indexOf ("--snapshot") + 1];
        const auto scaleArg = args[args.indexOf ("--snapshot") + 2];
        const float scale = scaleArg.containsOnly ("0123456789.") && scaleArg.isNotEmpty() ? scaleArg.getFloatValue() : 1.0f;
        NSynthAudioProcessor proc;
        std::unique_ptr<NSynthAudioProcessorEditor> editor (dynamic_cast<NSynthAudioProcessorEditor*> (proc.createEditor()));
        editor->setScale (scale);
        if (args.contains ("--browser"))
        {
            editor->openPresetBrowser (nSynth::PresetKind::patch);
            editor->getPresetBrowser().loadRow (2, false);
        }
        const auto image = editor->createComponentSnapshot (editor->getLocalBounds(), true, 1.0f);
        auto file = juce::File::getCurrentWorkingDirectory().getChildFile (path);
        file.deleteFile();
        juce::FileOutputStream out (file);
        const bool ok = out.openedOk() && juce::PNGImageFormat().writeImageToStream (image, out);
        std::cout << (ok ? "Wrote " : "FAILED to write ") << path << std::endl;
        return ok ? 0 : 1;
    }

    if (args.contains ("--list"))
    {
        for (auto* t : juce::UnitTest::getTestsInCategory ("nSynth"))
            std::cout << t->getName() << std::endl;
        return 0;
    }

    juce::UnitTestRunner runner;
    runner.setAssertOnFailure (false);

    if (args.contains ("--only"))
    {
        const auto name = args[args.indexOf ("--only") + 1];
        juce::Array<juce::UnitTest*> selected;
        for (auto* t : juce::UnitTest::getTestsInCategory ("nSynth"))
            if (t->getName() == name)
                selected.add (t);
        runner.runTests (selected);
    }
    else
    {
        runner.runTestsInCategory ("nSynth");
    }

    int failures = 0, passes = 0;
    for (int i = 0; i < runner.getNumResults(); ++i)
    {
        failures += runner.getResult (i)->failures;
        passes += runner.getResult (i)->passes;
    }
    std::cout << "\n==== nSynthTests: " << passes << " checks passed, " << failures << " failed ====" << std::endl;
    return failures > 0 ? 1 : 0;
}
